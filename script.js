function enhanceVideoCards() {
  document.querySelectorAll("[data-video-key]").forEach((card) => {
    const source = VIDEO_SOURCES[card.dataset.videoKey];
    if (!source?.src) return;

    const stage = card.querySelector(".video-stage");
    const title = card.querySelector("h3").textContent;

    if (source.type === "embed") {
      const iframe = document.createElement("iframe");
      iframe.src = source.src;
      iframe.title = title;
      iframe.loading = "lazy";
      iframe.allow = "autoplay; fullscreen; picture-in-picture";
      iframe.allowFullscreen = true;
      stage.replaceChildren(iframe);
    } else {
      const video = document.createElement("video");
      video.src = source.src;
      video.controls = true;
      video.preload = "metadata";
      video.playsInline = true;
      video.setAttribute("aria-label", title);
      stage.replaceChildren(video);
    }

    stage.classList.add("has-video");
  });
}

function setLanguage(language) {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value !== undefined) element.alt = value;
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAriaLabel];
    if (value !== undefined) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll(".language-button").forEach((button) => {
    const active = button.dataset.lang === language;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.title = language === "fr"
    ? "Cheikh Tidjani Tweylib — Ingénieur de recherche en IA"
    : "Cheikh Tidjani Tweylib — AI Research Engineer";

  try {
    localStorage.setItem("portfolio-language", language);
  } catch (_) {
    // The language switch still works if storage is unavailable.
  }
}

document.querySelectorAll(".language-button").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  },
  { threshold: 0.11, rootMargin: "0px 0px -40px" },
);

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

